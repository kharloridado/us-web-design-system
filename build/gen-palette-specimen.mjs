#!/usr/bin/env node
/* gen-palette-specimen.mjs — the Live Style Guide colour specimen.
 *
 * GENERATED, never hand-written, and derived from tokens/colors.css itself. Two outputs:
 *
 *   style-guide/palette-specimen.css   one class per token: background: var(--color-<x>)
 *   preview/index.html                 the swatch grid, between the specimen markers
 *
 * Why generated: the harness rule is that the preview's own chrome stays token-only and
 * class-only — no inline styles, no ad-hoc hex — because "a preview that cheats cannot tell
 * you whether the tokens are right". A hand-maintained specimen drifts from the palette the
 * moment a token moves, and a drifted specimen is worse than none: it shows you a colour the
 * build no longer emits. Deriving both files from the same source makes drift impossible.
 *
 * The hex appears as TEXT CONTENT beside each swatch, never as a CSS value. That is the
 * point of the specimen: the block is painted by `var(--token)` through the real cascade,
 * and the label says what it should be, so a mismatch is visible to the eye.
 *
 *   node build/gen-palette-specimen.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));

/* Ramp grouping mirrors the design's own two-palette split (see loop/refs/<id>/figma.png):
 * Theme palette first, then State palette, each ramp light -> dark. */
const SECTIONS = [
  { title: 'Theme palette', ramps: ['base', 'primary', 'secondary', 'accent-cool', 'accent-warm'] },
  { title: 'State palette', ramps: ['info', 'error', 'warning', 'success', 'disabled'] },
];

const src = readFileSync(join(root, 'tokens', 'colors.css'), 'utf8');

/* Same anchor the utilities generator uses: a declaration line, never a comment line. */
const tokens = [];
for (const m of src.matchAll(/^\s*(--color-([\w-]+))\s*:\s*([^;]+);/gm)) {
  tokens.push({ varName: m[1], leaf: m[2], value: m[3].trim() });
}
if (!tokens.length) {
  console.error('gen:palette-specimen — no --color-* tokens found in tokens/colors.css');
  process.exit(1);
}

/* Longest ramp prefix wins, so `accent-cool-dark` lands on `accent-cool`, not on a
 * hypothetical `accent`. Without this the two accent ramps collapse together. */
const allRamps = SECTIONS.flatMap((s) => s.ramps).sort((a, b) => b.length - a.length);
const rampOf = (leaf) => allRamps.find((r) => leaf === r || leaf.startsWith(r + '-')) ?? null;

const orphans = tokens.filter((t) => !rampOf(t.leaf));
if (orphans.length) {
  console.error(
    'gen:palette-specimen — token(s) match no known ramp: ' +
      orphans.map((t) => t.varName).join(', ') +
      '\n  Add the ramp to SECTIONS. Refusing to emit a specimen that silently omits a token.'
  );
  process.exit(1);
}

/* ---- 1. the stylesheet ---- */
const cssRules = tokens
  .map((t) => `.uswds-swatch--${t.leaf} { background-color: var(${t.varName}); }`)
  .join('\n');

const css = `/* GENERATED by build/gen-palette-specimen.mjs — do not edit.
 * Regenerate with \`npm run gen:palette-specimen\` after any change to tokens/colors.css.
 *
 * Live Style Guide chrome only. Every fill is var(--token): the swatch is painted through
 * the real cascade, so what you see is what the theme actually emits, not a copy of it. */

.uswds-specimen__section {
  margin-block-end: var(--space-l, 2rem);
}

.uswds-specimen__ramp {
  /* One ramp per row, never wrapped. A ramp split across two rows stops reading as a
   * progression, which is the one thing a palette specimen has to show. */
  display: flex;
  flex-wrap: nowrap;
  gap: var(--space-xs, 0.5rem);
  margin-block-end: var(--space-m, 1rem);
}

.uswds-specimen__item {
  /* Equal columns that share the row, so a 7-step ramp and a 3-step ramp both span the
   * full width and the steps stay comparable across ramps. */
  flex: 1 1 0;
  min-inline-size: 0;
}

.uswds-specimen__chip {
  block-size: 4rem;
  border-radius: 2px;
  /* A hairline so #FFFFFF-adjacent steps still read as a block against the page. */
  box-shadow: inset 0 0 0 1px rgb(0 0 0 / 12%);
}

.uswds-specimen__name {
  display: block;
  font-family: monospace;
  font-size: var(--font-size-s, 0.875rem);
  color: var(--color-base-ink);
  margin-block-start: var(--space-xs, 0.5rem);
  /* Break between hyphen segments, never mid-segment: a token name split as
   * --color-primary-lighte / r is harder to read than one wrapping at a hyphen. */
  overflow-wrap: break-word;
  word-break: normal;
}

.uswds-specimen__hex {
  display: block;
  font-family: monospace;
  font-size: var(--font-size-s, 0.875rem);
  color: var(--color-base-dark);
  text-transform: uppercase;
}

${cssRules}
`;

const cssPath = join(root, 'style-guide', 'palette-specimen.css');
mkdirSync(dirname(cssPath), { recursive: true });
writeFileSync(cssPath, css);

/* ---- 2. the markup ---- */
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const html = SECTIONS.map((section) => {
  const ramps = section.ramps
    .map((ramp) => {
      const items = tokens
        .filter((t) => rampOf(t.leaf) === ramp)
        .map(
          (t) =>
            `          <div class="uswds-specimen__item">\n` +
            `            <div class="uswds-specimen__chip uswds-swatch--${t.leaf}"></div>\n` +
            `            <code class="uswds-specimen__name">${esc(t.varName)}</code>\n` +
            `            <code class="uswds-specimen__hex">${esc(t.value)}</code>\n` +
            `          </div>`
        )
        .join('\n');
      return `        <h4>${esc(ramp)}</h4>\n        <div class="uswds-specimen__ramp">\n${items}\n        </div>`;
    })
    .join('\n');
  return `      <div class="uswds-specimen__section">\n        <h3>${esc(section.title)}</h3>\n${ramps}\n      </div>`;
}).join('\n');

const START = '<!-- BEGIN generated palette specimen -->';
const END = '<!-- END generated palette specimen -->';

const previewPath = join(root, 'preview', 'index.html');
let preview = readFileSync(previewPath, 'utf8');
const eol = preview.includes('\r\n') ? '\r\n' : '\n';

const block =
  `${START}${eol}` +
  `      <!-- GENERATED by build/gen-palette-specimen.mjs — do not hand-edit. -->${eol}` +
  html.split('\n').join(eol) +
  `${eol}      ${END}`;

const re = new RegExp(
  START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '[\\s\\S]*?' + END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
);

if (re.test(preview)) {
  preview = preview.replace(re, block);
} else {
  const anchor = '      <p><em>No components built yet.</em></p>';
  if (!preview.includes(anchor)) {
    console.error('gen:palette-specimen — could not find the specimen anchor in preview/index.html');
    process.exit(1);
  }
  preview = preview.replace(anchor, `      ${block}`);
}
writeFileSync(previewPath, preview);

/* ---- 3. the ODC screen ----
 *
 * The same specimen, repackaged as two pastes for an ODC Screen:
 *
 *   style-guide/odc-palette-screen.html  one Expression widget, Escape Content = No
 *   style-guide/odc-palette-screen.css   the Screen's Style Sheet
 *
 * Why a separate emit rather than reusing the preview's two files verbatim: in ODC the
 * Screen stylesheet is its OWN paste, loaded independently of the theme. So this CSS has
 * to be self-contained — it carries the layout rules AND the per-token swatch classes —
 * whereas the preview gets its layout from the harness page. The tokens themselves still
 * come from the theme, never from here.
 *
 * Both properties that make this a check rather than decoration are preserved: every chip
 * is painted by `var(--color-*)` through the live ODC cascade, and every hex is text
 * content. If the theme has not been pasted, the chips render unpainted next to labels
 * claiming a colour — which is the failure being tested for, made visible. */

const odcCss = `/* ${'GENERATED'} by build/gen-palette-specimen.mjs — do not edit.
 * Regenerate with \`npm run gen:palette-specimen\` after any change to tokens/colors.css.
 *
 * PASTE INTO: the ODC Screen's Style Sheet (Screen > Style Sheet), NOT the theme.
 * Requires dist/theme.css to already be pasted into the theme — this file consumes the
 * --color-* tokens, it does not define them.
 *
 * Token-only and class-only: no hard-coded design value, no inline style, and nothing
 * attached by mutating OutSystems UI internals. */

.uswds-specimen {
  font-family: var(--font-family-base);
  line-height: var(--line-height-base);
  color: var(--color-base-ink);
  padding: var(--space-l, 1.5rem);
}

.uswds-specimen__section {
  margin-block-end: var(--space-2xl, 3rem);
}

.uswds-specimen__section-title {
  margin: 0 0 var(--space-m, 1rem);
  padding-block-end: var(--space-s, 0.5rem);
  border-block-end: 2px solid var(--color-base-ink);
  font-size: var(--font-size-xl, 2rem);
  font-weight: var(--font-weight-bold, 700);
}

.uswds-specimen__ramp-title {
  margin: 0 0 var(--space-xs, 0.25rem);
  font-size: var(--font-size-lg, 1.375rem);
  font-weight: var(--font-weight-medium, 500);
  color: var(--color-base-darker);
  text-transform: capitalize;
}

.uswds-specimen__ramp {
  /* One ramp per row, never wrapped — a ramp split across two rows stops reading as a
   * progression, which is the one thing a palette specimen has to show. */
  display: flex;
  flex-wrap: nowrap;
  gap: var(--space-xs, 0.5rem);
  margin-block-end: var(--space-l, 1.5rem);
}

.uswds-specimen__item {
  /* Equal columns sharing the row, so a 7-step ramp and a 3-step ramp both span the full
   * width and the steps stay comparable across ramps. */
  flex: 1 1 0;
  min-inline-size: 0;
}

.uswds-specimen__chip {
  block-size: 4rem;
  border-radius: 2px;
  /* A hairline so #FFFFFF-adjacent steps still read as a block against the page. */
  box-shadow: inset 0 0 0 1px rgb(0 0 0 / 12%);
}

.uswds-specimen__name {
  display: block;
  font-family: monospace;
  font-size: var(--font-size-2xs, 0.875rem);
  color: var(--color-base-ink);
  margin-block-start: var(--space-xs, 0.5rem);
  /* Break between hyphen segments, never mid-segment. */
  overflow-wrap: break-word;
  word-break: normal;
}

.uswds-specimen__hex {
  display: block;
  font-family: monospace;
  font-size: var(--font-size-2xs, 0.875rem);
  color: var(--color-base-dark);
  text-transform: uppercase;
}

/* Phones: a 7-step ramp in a nowrap row leaves ~40px per chip, which stops being a
 * readable specimen. Stack instead — the progression still reads top-to-bottom. */
@media (max-width: 480px) {
  .uswds-specimen { padding: var(--space-m, 1rem); }
  .uswds-specimen__ramp { flex-wrap: wrap; }
  .uswds-specimen__item { flex: 1 1 40%; }
}

${cssRules}
`;
writeFileSync(join(root, 'style-guide', 'odc-palette-screen.css'), odcCss);

const odcHtml =
  `<!-- GENERATED by build/gen-palette-specimen.mjs — do not hand-edit.\n` +
  `     PASTE INTO: one Expression widget on the ODC screen, with Escape Content = No.\n` +
  `     Pair it with style-guide/odc-palette-screen.css in the Screen's Style Sheet.\n` +
  `     ${tokens.length} swatches, painted through the live cascade. -->\n` +
  `<div class="uswds-specimen">\n` +
  SECTIONS.map((section) => {
    const ramps = section.ramps
      .map((ramp) => {
        const items = tokens
          .filter((t) => rampOf(t.leaf) === ramp)
          .map(
            (t) =>
              `        <div class="uswds-specimen__item">\n` +
              `          <div class="uswds-specimen__chip uswds-swatch--${t.leaf}"></div>\n` +
              `          <code class="uswds-specimen__name">${esc(t.varName)}</code>\n` +
              `          <code class="uswds-specimen__hex">${esc(t.value)}</code>\n` +
              `        </div>`
          )
          .join('\n');
        return (
          `      <h3 class="uswds-specimen__ramp-title">${esc(ramp.replace(/-/g, ' '))}</h3>\n` +
          `      <div class="uswds-specimen__ramp">\n${items}\n      </div>`
        );
      })
      .join('\n');
    return (
      `  <section class="uswds-specimen__section">\n` +
      `    <h2 class="uswds-specimen__section-title">${esc(section.title)}</h2>\n${ramps}\n  </section>`
    );
  }).join('\n') +
  `\n</div>\n`;
writeFileSync(join(root, 'style-guide', 'odc-palette-screen.html'), odcHtml);

console.log(
  `gen:palette-specimen → style-guide/palette-specimen.css (${tokens.length} swatches) ` +
    `+ preview/index.html + style-guide/odc-palette-screen.{html,css}`
);
for (const s of SECTIONS) {
  const counts = s.ramps.map((r) => `${r}(${tokens.filter((t) => rampOf(t.leaf) === r).length})`);
  console.log(`  ${s.title}: ${counts.join(' ')}`);
}
