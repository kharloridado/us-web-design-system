#!/usr/bin/env node
/* gen-font-faces.mjs — generates the @font-face declarations that actually SHIP the
 * brand face, in the two places they have to exist with two different `src` paths.
 *
 *   tokens/font-faces.css   src: /<odcThemeModule>/PublicSans-*.woff2   (the ODC paste)
 *   preview/fonts.css       src: /vendor/public-sans/webfonts/*.woff2   (the local harness)
 *
 * WHY A GENERATOR AND NOT TWO HAND-WRITTEN FILES. The ODC `src` embeds
 * `odcThemeModule`, which is a project VALUE and lives in project.config.json (hard rule
 * #8). A CSS file cannot read config, so the choice is "generate it" or "type the module
 * name into CSS and let it drift the first time a project is renamed". Same reasoning as
 * build/optional/fontawesome/build-fontawesome.mjs, which rewrites the same `/${THEME}/`
 * prefix for exactly the same reason.
 *
 * The second output falls out for free, and pays for the script on its own: the preview
 * and the theme MUST declare the same family, the same five weights and the same styles,
 * or the harness stops being evidence about what ODC will render. Generating both from
 * one FACES table makes divergence impossible rather than merely unlikely.
 *
 * WHY THE PREVIEW NEEDS ITS OWN COPY AT ALL. The `src` in the theme is an ODC Resource
 * path. ODC rewrites and fingerprints it at compile time, so it resolves in the published
 * app and 404s everywhere else — including the local preview server (docs/LESSONS.md
 * §1.7: the literal path 404ing is EXPECTED; "fixing" it breaks the rewrite). Two
 * @font-face rules for the same family+weight+style do not cascade on failure — the LAST
 * one declared wins outright — so preview/fonts.css is linked AFTER dist/theme.css in
 * preview/index.html and its working local URL is the one the browser uses.
 *
 * FAMILY NAME: "Public Sans Web", not "Public Sans". That is upstream USWDS's own
 * display-name for the self-hosted face (uswds-core/styles/tokens/font/typefaces.scss),
 * and the distinction is load-bearing: it keeps the webfont separate from any copy of
 * Public Sans a user happens to have INSTALLED, which may be a different version. The
 * stack in tokens/typography.css lists "Public Sans" right after it, so a local install
 * is still a fallback — just not a silent substitute for the face we shipped.
 *
 * `font-display: fallback` and the woff2-only `src` are both USWDS's own choices
 * (at-font-face() and font-sources() with $theme-font-browser-compatibility: false).
 *
 * Usage:  node build/gen-font-faces.mjs   (or: npm run gen:font-faces)
 * Then:   npm run build:theme */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { projectConfig, root } from "./lib/project-config.mjs";

const cfg = projectConfig();
const THEME = cfg.odcThemeModule;

/* The five faces this design system actually uses. Every weight Public Sans ships that is
 * NOT here is absent on purpose — see vendor/public-sans/README.md for the table and the
 * reasoning. Adding a weight here means uploading one more ODC Resource, so it is a
 * deliberate act, not a default. */
const FACES = [
  { file: "PublicSans-Regular", weight: 400, style: "normal", why: "--font-weight-regular — body, h6, most UI text" },
  { file: "PublicSans-Italic", weight: 400, style: "italic", why: "<em> / <i> at body weight" },
  { file: "PublicSans-Medium", weight: 500, style: "normal", why: "--font-weight-medium — OSUI's --font-semi-bold, 33 emphasis rules" },
  { file: "PublicSans-Bold", weight: 700, style: "normal", why: "--font-weight-bold — display, h1-h5" },
  { file: "PublicSans-BoldItalic", weight: 700, style: "italic", why: "<em> inside a heading" },
];

const FAMILY = "Public Sans Web";

function faceBlock({ file, weight, style, why }, srcDir) {
  return [
    `/* ${weight} ${style} — ${why} */`,
    `@font-face {`,
    `  font-family: "${FAMILY}";`,
    `  font-style: ${style};`,
    `  font-weight: ${weight};`,
    `  font-display: fallback;`,
    `  src: url("${srcDir}${file}.woff2") format("woff2");`,
    `}`,
  ].join("\n");
}

/* ---- 1. tokens/font-faces.css — the ODC paste ------------------------------------ */
const odcHead = `/* @section Typography / Font faces */
/* font-faces.css — GENERATED by build/gen-font-faces.mjs. DO NOT EDIT BY HAND.
 * Rerun \`npm run gen:font-faces\` (it also rewrites preview/fonts.css), then
 * \`npm run build:theme\`.
 *
 * THIS FILE IS WHAT MAKES THE BRAND FACE REAL. tokens/typography.css NAMES the family;
 * naming it ships nothing. Without the five declarations below, every
 * var(--font-family-base) silently resolves to the first available fallback and the whole
 * app renders in the framework's default system sans.
 *
 * SOURCE OF RECORD for the family: loop/refs/tok-typography/ (Figma node 63-49) names
 * "Public Sans" on every one of its eight Prose steps. The BINARIES are upstream USWDS's
 * own release — vendor/public-sans/, Public Sans v2.001, SIL OFL 1.1, committed because
 * that licence permits redistribution (see that directory's README).
 *
 * FAMILY NAME IS "Public Sans Web", NOT "Public Sans". Upstream USWDS's display-name for
 * the self-hosted face. It keeps the shipped webfont distinct from whatever copy of
 * Public Sans a user may have installed locally, which can be a different version with
 * different metrics. tokens/typography.css lists "Public Sans" next in the stack, so a
 * local install still serves as a fallback — it just cannot silently impersonate ours.
 *
 * SRC PATHS ARE ODC RESOURCE PATHS, AND THEY 404 LOCALLY ON PURPOSE.
 * \`/${THEME}/PublicSans-*.woff2\` is rewritten and fingerprinted by ODC at compile time,
 * so the literal path resolves only in the published app. Fetching it anywhere else and
 * getting a 404 is EXPECTED and is not evidence of a bug — "fixing" the path is what
 * breaks the rewrite (docs/LESSONS.md §1.7). The five .woff2 must be uploaded as
 * Resources on the ${THEME} app; handover/public-sans-font-face.md carries that step.
 * The local preview gets working URLs from preview/fonts.css instead.
 *
 * IF TEXT FALLS BACK TO A SYSTEM SANS IN THE PUBLISHED APP, the cause is almost always a
 * WEIGHT USED BUT NEVER DECLARED HERE — check the used weights before you touch a URL.
 *
 * NO FRAMEWORK COLLISION. OutSystems UI declares no @font-face for a text family (it
 * hard-codes a system stack on \`html\`, line 949 of the compiled framework); the only
 * family it OWNS is its icon font, and redeclaring THAT name would clobber the native
 * Icon widget (vendor/LICENSING.md §3). "Public Sans Web" is ours alone.
 *
 * woff2 only, font-display: fallback — both are upstream USWDS's own choices
 * (at-font-face() / font-sources() with $theme-font-browser-compatibility: false). */\n`;

const odcCss =
  odcHead + "\n" + FACES.map((f) => faceBlock(f, `/${THEME}/`)).join("\n\n") + "\n";

/* ---- 2. preview/fonts.css — the local harness ------------------------------------ */
const previewHead = `/* fonts.css — GENERATED by build/gen-font-faces.mjs. DO NOT EDIT BY HAND.
 * Rerun \`npm run gen:font-faces\`.
 *
 * PREVIEW ONLY. NOT part of the theme and NOT pasted into ODC.
 *
 * Same family, same five weights and styles as tokens/font-faces.css — only the \`src\`
 * differs. The theme's \`src\` is an ODC Resource path that resolves only in a published
 * app; here it would 404 and the harness would render in a system sans, which would make
 * every typographic measurement it produces a lie.
 *
 * Two @font-face rules for one family+weight+style do NOT cascade on failure — the last
 * one declared wins outright. So this file MUST be linked AFTER ../dist/theme.css in
 * preview/index.html, and it deliberately re-declares rather than supplements.
 *
 * Paths are server-absolute because build/preview-server.mjs serves the PROJECT ROOT,
 * with the document at /preview/index.html. */\n`;

const previewCss =
  previewHead +
  "\n" +
  FACES.map((f) => faceBlock(f, "/vendor/public-sans/webfonts/")).join("\n\n") +
  "\n";

/* ---- 3. Guard: every declared face must actually exist in vendor/ ---------------- */
const missing = FACES.filter((f) => {
  try {
    readFileSync(join(root, "vendor", "public-sans", "webfonts", `${f.file}.woff2`));
    return false;
  } catch {
    return true;
  }
});
if (missing.length) {
  console.error(
    `gen:font-faces — missing font binaries in vendor/public-sans/webfonts/:\n` +
      missing.map((f) => `  ${f.file}.woff2`).join("\n") +
      `\nDeclaring a face whose file is absent is exactly the failure in docs/LESSONS.md §1.7.`
  );
  process.exit(1);
}

writeFileSync(join(root, "tokens", "font-faces.css"), odcCss);
writeFileSync(join(root, "preview", "fonts.css"), previewCss);
console.log(
  `gen:font-faces → tokens/font-faces.css + preview/fonts.css (${FACES.length} faces, family "${FAMILY}", ODC module ${THEME})`
);
